/* Ultra Paper — reproducible script generators for R (metafor), Stata 16+ (meta) and Python. */
(function () { 'use strict';
const S = window.UPStats;
const q = s => '"' + String(s ?? '').replace(/["\\]/g, '').replace(/\s+/g, ' ').trim() + '"';
const n = x => { const v = S.num(x); return Number.isFinite(v) ? String(+v.toPrecision(12)) : 'NA'; };
const vec = (rows, f) => 'c(' + rows.map(f).join(', ') + ')';
const RMETHOD = { REML: 'REML', DL: 'DL', PM: 'PM', ML: 'ML', HE: 'HE', SJ: 'SJ', FE: 'FE' };
const RTEST = { z: 'z', knha: 'knha', 'knha-adhoc': 'adhoc' };
const STMETHOD = { REML: 'random(reml)', DL: 'random(dlaird)', PM: 'random(ebayes)', ML: 'random(mle)', HE: 'random(hedges)', SJ: 'random(sjonkman)', FE: 'common' };
const stamp = c => `Generated by Ultra Paper Evidence Studio v3 — ${new Date().toISOString().slice(0, 10)}\n# Outcome: ${c.outcome || '-'} | Time point: ${c.timepoint || '-'} | Metric: ${c.metric} | tau2: ${c.method} | test: ${c.test} | level: ${c.level}%`;

function r(c) { const R = c.rows, M = c.metric, kind = S.METRICS[M].kind, tr = S.isRatio(M) ? 'exp' : M === 'PLO' ? 'transf.ilogit' : M === 'ZCOR' ? 'transf.ztor' : null;
  const T = tr ? `, transf = ${tr}` : '', AT = tr ? `, atransf = ${tr === 'exp' ? 'exp' : tr}` : '';
  let data = `dat <- data.frame(\n  study = ${vec(R, x => q(x.name))},\n  year  = ${vec(R, x => n(x.year))},\n  group = ${vec(R, x => q(x.group || 'Overall'))},\n  mod   = ${vec(R, x => n(x.mod))},\n  rob   = ${vec(R, x => q(x.rob))},\n`, es;
  if (kind === 'bin') { data += `  ai = ${vec(R, x => n(x.a))}, bi = ${vec(R, x => n(x.b))},\n  ci = ${vec(R, x => n(x.c))}, di = ${vec(R, x => n(x.d))}\n)`; es = `dat <- escalc(measure = "${M}", ai = ai, bi = bi, ci = ci, di = di, data = dat, slab = study)`; }
  else if (kind === 'cont') { data += `  m1i = ${vec(R, x => n(x.mean1))}, sd1i = ${vec(R, x => n(x.sd1))}, n1i = ${vec(R, x => n(x.n1))},\n  m2i = ${vec(R, x => n(x.mean0))}, sd2i = ${vec(R, x => n(x.sd0))}, n2i = ${vec(R, x => n(x.n0))}\n)`; es = `dat <- escalc(measure = "${M}", m1i = m1i, sd1i = sd1i, n1i = n1i, m2i = m2i, sd2i = sd2i, n2i = n2i, data = dat, slab = study)`; }
  else if (kind === 'prop') { data += `  xi = ${vec(R, x => n(x.xi))}, ni = ${vec(R, x => n(x.ni))}\n)`; es = `dat <- escalc(measure = "PLO", xi = xi, ni = ni, data = dat, slab = study)`; }
  else if (kind === 'cor') { data += `  ri = ${vec(R, x => n(x.ri))}, ni = ${vec(R, x => n(x.ni))}\n)`; es = `dat <- escalc(measure = "ZCOR", ri = ri, ni = ni, data = dat, slab = study)`; }
  else if (kind === 'genr') { data += `  est = ${vec(R, x => n(x.est))}, lower = ${vec(R, x => n(x.lower))}, upper = ${vec(R, x => n(x.upper))}\n)`; es = `dat$yi <- log(dat$est)\ndat$vi <- ((log(dat$upper) - log(dat$lower)) / (2 * qnorm(0.975)))^2\ndat <- escalc(measure = "GEN", yi = yi, vi = vi, data = dat, slab = study)`; }
  else { data += `  yi = ${vec(R, x => n(x.effect))}, sei = ${vec(R, x => n(x.se))}\n)`; es = `dat <- escalc(measure = "GEN", yi = yi, sei = sei, data = dat, slab = study)`; }
  const fit = `method = "${RMETHOD[c.method]}"${c.method === 'FE' ? '' : `, test = "${RTEST[c.test]}"`}, level = ${c.level}`;
  return `# ${stamp(c)}
# Requirements: install.packages(c("metafor"))   # R >= 4.1, metafor >= 4.0
library(metafor)

${data}
${es}

# ---- main model ------------------------------------------------------------
res <- rma(yi, vi, data = dat, ${fit})
print(res)
if (res$method != "FE") print(confint(res))   # Q-profile CI for tau^2, I^2, H^2
predict(res${T}, digits = 3)                  # pooled estimate + prediction interval

# ---- forest plot (also saved at 300 dpi) -------------------------------------
draw_forest <- function() forest(res${AT}, header = c("Study", "${M} [${c.level}% CI]"), ilab = dat$year, ilab.xpos = NULL,
  xlab = "${c.labelLeft ? c.labelLeft.replace(/"/g, '') + '  |  ' + (c.labelRight || '').replace(/"/g, '') : M}", addpred = TRUE, shade = TRUE, mlab = "${c.method === 'FE' ? 'Common-effect model' : 'Random-effects model'}")
draw_forest()
png("forest_plot.png", width = 2600, height = 400 + 110 * nrow(dat), res = 300); draw_forest(); dev.off()

# ---- small-study effects / publication bias -------------------------------------
funnel(res, level = c(90, 95, 99), shade = c("white", "gray80", "gray65"), refline = 0, legend = TRUE)
regtest(res)                                  # Egger-type regression test
ranktest(res)                                 # Begg & Mazumdar rank correlation
tf <- trimfill(res); print(tf); funnel(tf, legend = TRUE)

# ---- sensitivity / influence ---------------------------------------------------
leave1out(res${T}, digits = 3)
inf <- influence(res); print(inf); plot(inf)
baujat(res)
radial(res)
forest(cumul(res, order = order(dat$year))${AT})

# ---- subgroup & meta-regression ------------------------------------------------
if (length(unique(dat$group)) > 1) {
  for (g in unique(dat$group)) { cat("\\n== Subgroup:", g, "==\\n"); print(rma(yi, vi, data = dat, subset = group == g, ${fit})) }
  print(rma(yi, vi, mods = ~ factor(group), data = dat, ${fit}))   # test of moderators (QM)
}
if (sum(!is.na(dat$year)) >= 4) { mr <- rma(yi, vi, mods = ~ year, data = dat, ${fit}); print(mr); regplot(mr${AT}) }
if (sum(!is.na(dat$mod))  >= 4) { mr2 <- rma(yi, vi, mods = ~ mod, data = dat, ${fit}); print(mr2); regplot(mr2${AT}) }

write.csv(dat, "ultra_paper_escalc.csv", row.names = FALSE)
sessionInfo()
`; }

function stata(c) { const R = c.rows, M = c.metric, kind = S.METRICS[M].kind, st = STMETHOD[c.method];
  const se = c.method === 'FE' || c.test === 'z' ? '' : c.test === 'knha' ? ' se(khartung)' : ' se(khartung, truncated)';
  const tr = S.isRatio(M) ? ' eform' : M === 'PLO' ? ' transform(invlogit)' : M === 'ZCOR' ? ' transform(corr)' : '';
  let vars, rowsTxt, set;
  const base = x => `${q(x.name)} ${n(x.year) === 'NA' ? '.' : n(x.year)} ${q(x.group || 'Overall')} ${n(x.mod) === 'NA' ? '.' : n(x.mod)}`;
  if (kind === 'bin') { vars = 'double(a b c d)'; rowsTxt = R.map(x => `${base(x)} ${n(x.a)} ${n(x.b)} ${n(x.c)} ${n(x.d)}`); set = `meta esize a b c d, esize(${M === 'RR' ? 'lnrratio' : M === 'OR' ? 'lnoratio' : 'rdiff'}) ${st} studylabel(study)`; }
  else if (kind === 'cont') { vars = 'double(n1 m1 sd1 n0 m0 sd0)'; rowsTxt = R.map(x => `${base(x)} ${n(x.n1)} ${n(x.mean1)} ${n(x.sd1)} ${n(x.n0)} ${n(x.mean0)} ${n(x.sd0)}`); set = `meta esize n1 m1 sd1 n0 m0 sd0, esize(${M === 'MD' ? 'mdiff' : 'hedgesg'}) ${st} studylabel(study)`; }
  else { vars = 'double(yi sei)'; rowsTxt = R.map(x => `${base(x)} ${n(x._yi)} ${n(Math.sqrt(x._vi))}`); set = `meta set yi sei, ${st} studylabel(study)`; }
  return `* ${stamp(c).replace(/\n# /g, '\n* ')}
* Requires Stata 16+ (leaveoneout/cumulative need Stata 17+). Precomputed yi/sei are on the analysis scale.
version 16
clear all
set more off
input str80 study year str40 group mod ${vars}
${rowsTxt.join('\n')}
end

${set}
meta summarize,${tr}${se} level(${c.level})
meta forestplot,${tr}${se} level(${c.level})
graph export "forest_plot.png", width(2400) replace

* --- small-study effects ---
meta funnelplot, contours(1 5 10)
meta bias, egger
meta bias, begg
meta trimfill,${tr} funnel

* --- heterogeneity explorations ---
capture noisily meta summarize, subgroup(group)${tr}
capture noisily meta regress year${se}
capture noisily estat bubbleplot
capture noisily meta regress mod${se}
capture noisily meta summarize, leaveoneout${tr}
capture noisily meta summarize, cumulative(year)${tr}
`; }

function python(c) { const R = c.rows, M = c.metric;
  return `# ${stamp(c)}
# Requirements: pip install numpy scipy pandas matplotlib
import numpy as np, pandas as pd, matplotlib.pyplot as plt
from scipy import stats, optimize

df = pd.DataFrame({
    "study": [${R.map(x => q(x.name)).join(', ')}],
    "year":  [${R.map(x => n(x.year) === 'NA' ? 'np.nan' : n(x.year)).join(', ')}],
    "group": [${R.map(x => q(x.group || 'Overall')).join(', ')}],
    "yi":    [${R.map(x => n(x._yi)).join(', ')}],   # analysis scale (${S.METRICS[M].scale})
    "vi":    [${R.map(x => n(x._vi)).join(', ')}],
})
METHOD, TEST, LEVEL = "${c.method}", "${c.test}", ${c.level}
BACK = ${S.isRatio(M) ? 'np.exp' : M === 'PLO' ? '(lambda x: 1 / (1 + np.exp(-x)))' : M === 'ZCOR' ? 'np.tanh' : '(lambda x: x)'}

def tau2_est(y, v, method):
    k = len(y); w = 1 / v; mu = np.sum(w * y) / w.sum(); Q = np.sum(w * (y - mu) ** 2)
    if method == "FE" or k < 2: return 0.0
    dl = max(0.0, (Q - (k - 1)) / (w.sum() - np.sum(w ** 2) / w.sum()))
    if method == "DL": return dl
    def score(t):
        ww = 1 / (v + t); m = np.sum(ww * y) / ww.sum(); s = np.sum(ww ** 2 * (y - m) ** 2) - ww.sum()
        if method == "REML": s += np.sum(ww ** 2) / ww.sum()
        if method == "PM": s = np.sum(ww * (y - m) ** 2) - (k - 1)
        return s
    if method not in ("REML", "ML", "PM"): method = "REML"
    if score(0) <= 0: return 0.0
    hi = max(dl, 1e-4)
    while score(hi) > 0: hi *= 2
    return optimize.brentq(score, 0, hi, xtol=1e-12)

def meta(y, v, method=METHOD, test=TEST, level=LEVEL):
    k = len(y); t2 = tau2_est(y, v, method); w = 1 / (v + t2); mu = np.sum(w * y) / w.sum(); se = np.sqrt(1 / w.sum())
    a = 1 - level / 100; crit = stats.norm.ppf(1 - a / 2); dist = "z"
    if method != "FE" and test in ("knha", "knha-adhoc") and k > 1:
        qs = np.sum(w * (y - mu) ** 2) / (k - 1); se *= np.sqrt(max(1, qs) if test == "knha-adhoc" else qs)
        crit = stats.t.ppf(1 - a / 2, k - 1); dist = "t"
    p = 2 * (stats.t.sf(abs(mu / se), k - 1) if dist == "t" else stats.norm.sf(abs(mu / se)))
    wf = 1 / v; mf = np.sum(wf * y) / wf.sum(); Q = np.sum(wf * (y - mf) ** 2)
    I2 = max(0, (Q - (k - 1)) / Q) * 100 if k > 1 and Q > 0 else 0.0
    return dict(k=k, mu=mu, se=se, lo=mu - crit * se, hi=mu + crit * se, p=p, tau2=t2, Q=Q, I2=I2, w=w / w.sum() * 100)

y, v = df.yi.to_numpy(float), df.vi.to_numpy(float)
r = meta(y, v)
print(f"k={r['k']}  pooled=${M} {BACK(r['mu']):.3f} [{BACK(r['lo']):.3f}, {BACK(r['hi']):.3f}]  p={r['p']:.4g}")
print(f"tau2={r['tau2']:.4f}  Q={r['Q']:.3f}  I2(Q-based)={r['I2']:.1f}%")

# Egger regression (classical)
se_i = np.sqrt(v); eg = stats.linregress(1 / se_i, y / se_i)
t = eg.intercept / eg.intercept_stderr; print(f"Egger intercept={eg.intercept:.3f}, p={2 * stats.t.sf(abs(t), len(y) - 2):.4f}")

# Leave-one-out
for i in range(len(y)):
    m = np.arange(len(y)) != i; rr = meta(y[m], v[m])
    print(f"without {df.study[i]:<30} {BACK(rr['mu']):.3f} [{BACK(rr['lo']):.3f}, {BACK(rr['hi']):.3f}]  I2={rr['I2']:.1f}%")

# Forest plot
z = stats.norm.ppf(1 - (1 - LEVEL / 100) / 2); k = len(y)
fig, ax = plt.subplots(figsize=(9, 0.42 * k + 2))
for i in range(k):
    ax.plot(BACK(np.array([y[i] - z * se_i[i], y[i] + z * se_i[i]])), [k - i] * 2, color="#4d8271")
    ax.scatter(BACK(y[i]), k - i, marker="s", s=20 + 180 * r["w"][i] / r["w"].max(), color="#709e8d", zorder=3)
ax.fill([BACK(r["lo"]), BACK(r["mu"]), BACK(r["hi"]), BACK(r["mu"])], [0, 0.3, 0, -0.3], color="#e79479")
ax.set_yticks(list(range(k, 0, -1)) + [0], list(df.study) + ["Pooled"])
${S.isRatio(M) ? 'ax.set_xscale("log"); ax.axvline(1, color="grey", lw=.8)' : S.nullValue(M) === 0 ? 'ax.axvline(0, color="grey", lw=.8)' : ''}
ax.set_xlabel("${M}"); fig.tight_layout(); fig.savefig("forest_plot.png", dpi=300)

# Funnel plot
fig, ax = plt.subplots(figsize=(6, 5)); ax.scatter(y, se_i, color="#4d8271")
s = np.linspace(0, se_i.max() * 1.1, 50); ax.plot(r["mu"] - 1.96 * s, s, "--", color="grey"); ax.plot(r["mu"] + 1.96 * s, s, "--", color="grey")
ax.axvline(r["mu"], color="#e79479"); ax.invert_yaxis(); ax.set_xlabel("yi (analysis scale)"); ax.set_ylabel("SE")
fig.tight_layout(); fig.savefig("funnel_plot.png", dpi=300)
df.to_csv("ultra_paper_analysis_data.csv", index=False)
`; }

function csv(c) { const h = ['study', 'year', 'group', 'mod', 'rob', 'verified', 'source', 'page', 'yi', 'vi', 'sei']; return '\ufeff' + [h.join(','), ...c.rows.map(x => [q(x.name), n(x.year), q(x.group), n(x.mod), q(x.rob), x.verified ? 'TRUE' : 'FALSE', q(x.sourcePaper), n(x.sourcePage), n(x._yi), n(x._vi), n(Math.sqrt(x._vi))].map(v => v === 'NA' ? '' : v).join(','))].join('\r\n'); }

window.UPCode = { r, stata, python, csv };
})();
